# 例子：根据 HTTP 状态码判断结果
# 200=成功  301/302=跳转  403=禁止  404=不存在  500=服务器错误

status_code = 200  # 试试改成 404、403、500 看看

if status_code == 200:
    print("200 OK — 页面正常存在 ✅")
elif status_code == 301 or status_code == 302:
    print("301/302 — 页面跳转了 🔀")
elif status_code == 403:
    print("403 Forbidden — 页面存在但被禁止 🚫")
elif status_code == 404:
    print("404 Not Found — 页面不存在 ❌")
elif status_code == 500:
    print("500 Server Error — 服务器炸了，可能有漏洞 💣")
else:
    print(f"{status_code} — 其他状态码 ❓")

