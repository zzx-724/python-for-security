# for vs while 怎么选？
#   for   → 你知道要循环【多少个】（遍历列表、遍历数字范围）
#   while → 你不知道要循环多少次，只知道【什么条件下继续】

# 安全场景：重试请求。你不知道第几次能成功，只知道"没成功就继续试"
max_retry = 3          # 最多试 3 次
attempt = 0            # 已经试了几次

while attempt < max_retry:
    attempt += 1       # ⚠️ 千万别忘这行，否则永远出不去 = 死循环！
    print(f"  第 {attempt} 次尝试连接...")
    if attempt == 2:
        print("  [+] 第 2 次成功了，退出循环")
        break          # break = 立刻跳出循环
else:
    # 注意！while 的 else 是"循环正常跑完（没被 break）"才执行
    # 这个语法比较冷门，先知道有这么回事即可
    print("  [-] 3 次都失败了")

# ⚠️ 死循环警告：如果忘了 attempt += 1，程序会永远打印，只能 Ctrl+C 强制停


