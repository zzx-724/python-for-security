print("=" * 45)

# 这就是你在 Day 3 文件末尾看到、当时觉得超纲的东西。现在能看懂了。

all_ports = [21, 22, 23, 25, 53, 80, 110, 143, 443, 445, 3306, 3389, 8080, 8443]

# --- 先看"笨写法"（for + if + append，你在 Day 3 学过这三样）---
web_ports = []                          # 1. 准备空列表
for p in all_ports:                     # 2. 遍历
    if p in (80, 443, 8080, 8443):      # 3. 判断
        web_ports.append(p)             # 4. 收集
print(f"笨写法结果: {web_ports}")

# --- 再看"推导式写法"（同样的意思，一行）---
web_ports_2 = [p for p in all_ports if p in (80, 443, 8080, 8443)]
#               ↑    ↑          ↑
#             要什么  从哪遍历   什么条件
print(f"推导式结果: {web_ports_2}")

# --- 怎么读推导式？从【中间】往两边读 ---
#   [p          for p in all_ports        if p in (...)]
#    ↑          ↑                          ↑
#   拿什么出来   从哪里拿                    拿哪些（过滤条件）
# 读作："把 all_ports 里每一个 p，满足条件的，组成新列表"

# --- 推导式还能做转换 ---
big_ports = [p * 10 for p in [1, 2, 3]]
print(f"\n转换: {big_ports}")            # [10, 20, 30]

# --- 字典推导式（加个冒号就不是列表了）---
status_table = {p: "closed" for p in [22, 80, 443]}
print(f"字典推导式: {status_table}")     # {22: 'closed', 80: 'closed', 443: 'closed'}

# --- 嵌套推导式（两个 for，注意顺序和嵌套循环一样）---
urls = [f"http://{ip}:{port}" for ip in ["a.com", "b.com"] for port in [80, 8080]]
print(f"嵌套推导式: {urls}")

# ⚠️ 什么都要用推导式吗？不是！
# 简单的一行过滤/转换 → 推导式（清晰）
# 逻辑复杂、要写好几步 → 老实写 for 循环（可读）
# 可读性 > 炫技。别人看不懂的"聪明代码"是负分。


