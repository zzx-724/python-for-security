# --- zip：两个列表【并排】一起遍历 ---
# 解决的问题：端口和它对应的服务名在两个列表里，想配对输出
print("\n端口 ↔ 服务对照:")
port_list = [22, 80, 443, 3306]
service_list = ["SSH", "HTTP", "HTTPS", "MySQL"]

for port, service in zip(port_list, service_list):
    print(f"  {port:6d} → {service}")

# zip 会"拉链式"地把两个列表配对：
#   22 ↔ "SSH"      80 ↔ "HTTP"     443 ↔ "HTTPS"    3306 ↔ "MySQL"
# ⚠️ 如果两个列表长度不同，以【短的】为准，多出来的会被丢掉


