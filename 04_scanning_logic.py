# --- enumerate：同时拿到【序号】和【元素】---
# 解决的问题：想输出"1. 22  2. 80  3. 443"，用普通 for 拿不到序号
# ports = [22, 80, 443, 3306, 8080]
print("带序号的端口表:")
for i, port in enumerate(ports, 1):    # 第二个参数 1 = 序号从 1 开始（默认是 0）
    print(f"  {i}. 端口 {port}")

